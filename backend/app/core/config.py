"""Application configuration, read from the environment.

The session token is generated by the Tauri core at launch and passed through
the environment; it is never read from or written to disk here.
"""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="STAGE_FINDER_", extra="ignore")

    session_token: str | None = None
    host: str = "127.0.0.1"
    port: int = 8000
    log_level: str = "info"


@lru_cache
def get_settings() -> Settings:
    return Settings()
