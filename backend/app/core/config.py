"""Application configuration, read from the environment.

The session token is generated by the Tauri core at launch and passed through
the environment; it is never read from or written to disk here.
"""

import os
import sys
from functools import lru_cache
from pathlib import Path

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


def default_data_dir() -> Path:
    """Platform-specific per-user data directory for the local database."""
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "stage-finder"
    if os.name == "nt":
        base = os.environ.get("LOCALAPPDATA")
        if base:
            return Path(base) / "stage-finder"
        return Path.home() / "AppData" / "Local" / "stage-finder"
    base = os.environ.get("XDG_DATA_HOME")
    if base:
        return Path(base) / "stage-finder"
    return Path.home() / ".local" / "share" / "stage-finder"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="STAGE_FINDER_", extra="ignore")

    session_token: str | None = None
    host: str = "127.0.0.1"
    port: int = 8000
    log_level: str = "info"
    data_dir: Path = Field(default_factory=default_data_dir)

    @property
    def db_path(self) -> Path:
        return self.data_dir / "stage-finder.db"


@lru_cache
def get_settings() -> Settings:
    return Settings()
